from pyo import Beat
"""
Beat(time=0.125, taps=16, w1=80, w2=50, w3=30, poly=1, onlyonce=False)

Generates algorithmic trigger patterns.

A trigger is an audio signal with a value of 1 surrounded by 0s.

Beat generates measures of length `taps` and uses weight parameters
(`w1`, `w2` and `w3`) to compute the chances of a beat to be present
in the generated measure.

User can store the current pattern in one of the 32 preset slots with
the store() method and recall it later with recall(x).

A preset is a list where the first value is the number of beats in the
measure, followed by 1s and 0s. For a 4/4 measure with only down beats:

[16, 1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0]

The play() method starts the Beat and is not called at the object
creation time.

Params:
    time     -- Time, in seconds, between each beat of the pattern. Defaults to 0.125.
    taps     -- Number of beats in the generated pattern, max = 64. Defaults to 16.
    w1       -- Probability for down beats. Defaults to 80.
    w2       -- Probability for up beats. Defaults to 50.
    w3       -- Probability for the weakest beats. Defaults to 30.
    poly     -- Beat polyphony. Denotes how many independent streams are generated by the object, allowing overlapping processes. Available only at initialization. Defaults to 1.
    onlyonce -- If True, the sequence will play only once and automatically stop. Defaults to False.
"""

