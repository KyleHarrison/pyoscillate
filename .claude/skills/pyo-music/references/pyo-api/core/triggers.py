from pyo import TrigXnoiseMidi
"""
TrigXnoiseMidi(input, dist=0, x1=0.5, x2=0.5, scale=0, mrange=(0, 127), mul=1, add=0)

Triggered X-class midi notes pseudo-random generator.

Xnoise implements a few of the most common noise distributions.
A new value is generated each time the object receive a trigger
in input. Each distribution generates integer values in the range
defined with `mrange` parameter and output can be scaled on midi
notes, hertz or transposition factor.

Params:
    input  -- Audio signal sending triggers.
    dist   -- Distribution type. Defaults to 0.
    x1     -- First parameter. Defaults to 0.5.
    x2     -- Second parameter. Defaults to 0.5.
    scale  -- Output format. 0 = MIDI, 1 = Hertz, 2 = transposition factor. Defaults to 0. In the transposition mode, the central key (the key where there is no transposition) is (`minrange` + `maxrange`) / 2.
    mrange -- Minimum and maximum possible values, in Midi notes. Available only at initialization time. Defaults to (0, 127).
"""

from pyo import Counter
"""
Counter(input, min=0, max=100, dir=0, mul=1, add=0)

Integer count generator.

Counter keeps track of all triggers received, outputs the current
count constrained within `min` and `max` range, and can be set to
count up, down, or up-and-down.

Params:
    input -- Audio signal sending triggers.
    min   -- Minimum value of the count, included in the count. Defaults to 0.
    max   -- Maximum value of the count. excluded of the count. The counter will count up to max - 1. Defaults to 100.
    dir   -- Direction of the count. Defaults to 0. Three possible values: 0. up 1. down 2. up-and-down
"""

