from pyo import TrigBurst
"""
TrigBurst(input, time=0.25, count=10, expand=1.0, ampfade=1.0, poly=1)

Generates a time/amplitude expandable trigger pattern.

A trigger is an audio signal with a value of 1 surrounded by 0s.

When TrigBurst receives a trigger in its `input` argument, it starts
to output `count` triggers with a variable delay between each trigger
of the pattern. If `expand` is less than 1.0, the delay becomes shorter,
if it is greater than 1.0, the delay becomes longer.

Params:
    input   -- Input signal sending triggers.
    time    -- Base time, in seconds, between each trig of the serie. Defaults to 0.25.
    count   -- Number of trigs generated (length of the serie). Defaults to 10.
    expand  -- Timing power serie factor. Each delay before the next trig is the current delay (starting with `time`) times `expand` factor. Defaults to 1.0.
    ampfade -- Amplitude power serie factor. Each amplitude in the serie is the current amplitude (starting at 1) times `ampfade` factor. Defaults to 1.0.
    poly    -- Voice polyphony. Denotes how many independent streams are generated by the object, allowing overlapping processes. Available only at initialization. Defaults to 1.
"""
