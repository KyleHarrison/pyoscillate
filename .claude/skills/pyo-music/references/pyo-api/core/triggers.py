from pyo import Thresh
"""
Thresh(input, threshold=0.0, dir=0, mul=1, add=0)

Informs when a signal crosses a threshold.

Thresh sends a trigger when a signal crosses a threshold. The `dir`
parameter can be used to set the crossing mode, down-up, up-down, or
both.

Params:
    input     -- Audio signal sending triggers.
    threshold -- Threshold value. Defaults to 0.
    dir       -- There are three modes of using Thresh: 0. down-up (default) sends a trigger when current value is higher than the threshold, while old value was equal to or lower than the threshold. 1. up-down sends a trigger when current value is lower than the threshold, while old value was equal to or higher than the threshold. 2. both direction sends a trigger in both the two previous cases.
"""

